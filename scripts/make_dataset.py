#!/usr/bin/env python
"""Generate the custom dataset and its provenance record.

    python scripts/make_dataset.py                 # the published dataset
    python scripts/make_dataset.py --preset tiny   # what CI generates

The presets are the only thing that differs between the published run and CI.
Both go through the same generator, so a test that passes on ``tiny`` is
testing the code that produced the published numbers.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import _bootstrap  # noqa: F401
from edgetrack.data.dataset import dataset_summary, write_dataset_json, write_split
from edgetrack.data.synth import CLASSES, config_for_split

PRESETS = {
    # name: (train sequences, val sequences, test sequences, frames per train/val sequence)
    "full": (60, 15, 12, 24),
    "small": (16, 4, 4, 16),
    "tiny": (4, 2, 2, 8),
}


def build_configs(preset: str, seed: int) -> dict[str, list]:
    n_train, n_val, n_test, frames = PRESETS[preset]
    train = [
        config_for_split("train", seed + i, n_frames=frames) for i in range(n_train)
    ]
    val = [
        config_for_split("val", seed + 10_000 + i, n_frames=frames) for i in range(n_val)
    ]
    # Test sequences keep their long default length even on the small presets:
    # tracking metrics on an eight frame sequence are meaningless, and the cost
    # of the extra frames is a few seconds.
    test_frames = 120 if preset == "full" else (60 if preset == "small" else 24)
    test = [
        config_for_split("test", seed + 20_000 + i, n_frames=test_frames)
        for i in range(n_test)
    ]
    return {"train": train, "val": val, "test": test}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--root", default="data/processed", type=Path)
    parser.add_argument("--preset", default="full", choices=sorted(PRESETS))
    parser.add_argument("--seed", default=1000, type=int)
    parser.add_argument("--splits", nargs="*", default=None,
                        help="regenerate only these splits (default: all)")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    root = Path(args.root)
    configs = build_configs(args.preset, args.seed)
    if args.splits:
        configs = {k: v for k, v in configs.items() if k in set(args.splits)}
        if not configs:
            raise ValueError(f"no known split among {args.splits}")

    started = time.perf_counter()
    stats = {}
    for split, split_configs in configs.items():
        if not args.quiet:
            print(f"rendering {split}: {len(split_configs)} sequences", flush=True)
        # MOT ground truth for val as well as test.  Tracker parameters are
        # chosen on val by scripts/tune_tracker.py, and choosing them on the
        # split the headline numbers come from would make those numbers a
        # training score.
        stats[split] = write_split(
            root, split, split_configs, write_mot=(split in ("val", "test"))
        )

    summary = dataset_summary(
        root,
        stats,
        seeds={name: [c.seed for c in cfgs] for name, cfgs in configs.items()},
        configs={name: cfgs[0] for name, cfgs in configs.items()},
    )
    summary["partial"] = bool(args.splits)
    summary["preset"] = args.preset
    summary["seconds"] = round(time.perf_counter() - started, 2)
    write_dataset_json(root, summary)

    # The YOLO data yaml has to point at absolute paths or Ultralytics resolves
    # them against its own settings directory, which is a different place on
    # every machine and the single most common cause of "dataset not found".
    yaml_path = root / "data.yaml"
    yaml_path.write_text(
        "\n".join(
            [
                "# Generated by scripts/make_dataset.py.  Do not edit by hand.",
                f"path: {root.resolve().as_posix()}",
                "train: images/train",
                "val: images/val",
                "test: images/test",
                "names:",
                *[f"  {i}: {name}" for i, name in enumerate(CLASSES)],
                "",
            ]
        ),
        encoding="utf-8",
    )

    if not args.quiet:
        print(json.dumps({k: v.as_dict() for k, v in stats.items()}, indent=2))
        print(f"wrote {root/'dataset.json'} and {yaml_path} in {summary['seconds']}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python
"""Side by side: the YOLOv8n detector this repository used to ship and YOLOX-Tiny.

    python scripts/compare_detectors.py

Writes ``results/published/detector_comparison.json``.  The YOLOv8n numbers are
read from ``results/published/`` as it stood at the last commit before the
swap (``--baseline-ref``), through ``git show``, so they are the published
measurements rather than numbers retyped from memory.  The YOLOX-Tiny numbers
are the current published files.  Every delta is new minus old, so a negative
accuracy delta or a positive latency delta means the new detector is worse.

The two were measured with the same scripts on the same machine, a desktop RTX
4060 and its CPU but not on the same day, so latency differences of a few per
cent are within run-to-run variation; accuracy differences are exact, because
the dataset is regenerated byte for byte from its seeds.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import _bootstrap  # noqa: F401
from edgetrack.paths import write_text_lf

PUBLISHED = Path("results/published")


def at_ref(ref: str, name: str) -> dict:
    blob = subprocess.run(
        ["git", "show", f"{ref}:{(PUBLISHED / name).as_posix()}"],
        check=True, capture_output=True,
    ).stdout
    return json.loads(blob.decode("utf-8"))


def current(name: str) -> dict:
    return json.loads((PUBLISHED / name).read_text(encoding="utf-8"))


def summarise(load) -> dict:
    detection = load("detection.json")
    by_name = {}
    for name, entry in detection["variants"].items():
        variant = name.split("_edgetrack_")[-1]
        by_name[variant] = {
            "map50": entry["metrics"]["map50"],
            "map50_95": entry["metrics"]["map50_95"],
            "per_class_map50_95": entry["per_class_ap50_95_named"],
        }
    quantisation = load("quantisation.json")
    train = load("train.json")
    val = train.get("yolox_val") or train.get("ultralytics_val")
    latency = {r["name"]: r for r in load("latency.json")["results"]}
    trt = {r["precision"]: r for r in load("tensorrt.json")["rows"]}
    tracking = load("tracking.json")["trackers"]
    histogram = load("tracking_histogram.json")["trackers"]["deepsort"]["aggregate"]
    probe = load("launch_bound.json")["verdict"]
    return {
        "val_map50_95": val["map50_95"],
        "test": by_name,
        "int8_bytes": quantisation["int8"]["bytes"],
        "fp32_bytes": quantisation["int8"]["fp32_bytes"],
        "onnx_cpu_fp32_inference_p50_ms": latency["onnx-cpu-fp32"]["stages_ms"]["inference"]["p50"],
        "torch_cuda_fp32_inference_p50_ms":
            latency["torch-cuda-fp32"]["stages_ms"]["inference"]["p50"],
        "tensorrt": {
            p: {"map50_95": r["map50_95"], "inference_p50_ms": r["inference_p50_ms"],
                "engine_bytes": r["engine_bytes"],
                "map50_95_delta_vs_onnxruntime_fp32": r["map50_95_delta_vs_onnxruntime_fp32"]}
            for p, r in trt.items()
        },
        "tracking": {
            name: {k: entry["aggregate"][k] for k in
                   ("mota", "idf1", "num_switches", "num_false_positives", "num_misses")}
            for name, entry in tracking.items()
        },
        "deepsort_histogram": {k: histogram[k] for k in ("mota", "idf1", "num_switches")},
        "launch_bound_batch_time_ratio": probe["batch_time_ratio"],
    }


def delta(new, old):
    if isinstance(new, dict):
        return {k: delta(new[k], old[k]) for k in new if k in old}
    if isinstance(new, (int, float)) and isinstance(old, (int, float)):
        return round(new - old, 5)
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--baseline-ref", default="9a1d9ae",
                        help="the last commit whose results/published is YOLOv8n's")
    parser.add_argument("--out", default=PUBLISHED / "detector_comparison.json", type=Path)
    args = parser.parse_args(argv)

    old = summarise(lambda name: at_ref(args.baseline_ref, name))
    new = summarise(current)
    report = {
        "note": "YOLOv8n numbers are results/published at the baseline commit; YOLOX-Tiny "
                "numbers are the current results/published.  delta is YOLOX-Tiny minus "
                "YOLOv8n.",
        "baseline_ref": args.baseline_ref,
        "yolov8n": old,
        "yolox_tiny": new,
        "delta": delta(new, old),
    }
    write_text_lf(args.out, json.dumps(report, indent=2) + "\n")
    print(json.dumps(report["delta"], indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python
"""Break the ID-switch count down by cause and write the markdown table.

    python scripts/analyse_idswitches.py --tracking results/tracking.json \\
                                         --out docs/tables/idswitch_table.md

Reads the per-sequence records ``scripts/eval_tracking.py`` produced and turns
them into the table in ``docs/results.md``, plus the worst-case examples worth
looking at by hand.  Everything here is derived from the tracking run; nothing
is recomputed, so the table cannot disagree with the metrics above it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import _bootstrap  # noqa: F401
from edgetrack.metrics.idswitch import CAUSES
from edgetrack.paths import serialise_path, write_text_lf


def table(trackers: dict) -> str:
    names = list(trackers)
    lines = [
        "| cause | " + " | ".join(names) + " |",
        "| --- | " + " | ".join("---:" for _ in names) + " |",
    ]
    for cause in CAUSES:
        row = [str(trackers[name]["switch_causes"].get(cause, 0)) for name in names]
        lines.append(f"| {cause} | " + " | ".join(row) + " |")
    totals = [str(sum(trackers[name]["switch_causes"].values())) for name in names]
    lines.append("| **total** | " + " | ".join(f"**{t}**" for t in totals) + " |")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--tracking", default="results/tracking.json", type=Path)
    parser.add_argument("--out", default="docs/tables/idswitch_table.md", type=Path)
    parser.add_argument("--json-out", default="results/idswitches.json", type=Path)
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args(argv)

    if not args.tracking.exists():
        raise FileNotFoundError(
            f"{args.tracking} not found; run `python scripts/eval_tracking.py` first"
        )
    report = json.loads(args.tracking.read_text(encoding="utf-8"))
    trackers = report["trackers"]

    summary = {
        "source": serialise_path(args.tracking),
        "detections": report.get("detections"),
        "causes": {name: entry["switch_causes"] for name, entry in trackers.items()},
        "totals": {
            name: sum(entry["switch_causes"].values()) for name, entry in trackers.items()
        },
        "switches_per_hundred_frames": {},
        "worst_sequences": {},
    }
    for name, entry in trackers.items():
        frames = sum(
            seq["num_objects"] for seq in entry["per_sequence"].values()
        )
        summary["switches_per_hundred_frames"][name] = round(
            100.0 * entry["aggregate"]["num_switches"] / max(frames, 1), 4
        )
        ranked = sorted(
            entry["per_sequence"].items(),
            key=lambda item: -item[1]["num_switches"],
        )
        summary["worst_sequences"][name] = [
            {
                "sequence": seq_name,
                "switches": seq["num_switches"],
                "idf1": seq["idf1"],
                "causes": seq["switch_causes"],
            }
            for seq_name, seq in ranked[:3]
        ]

    markdown = "\n".join(
        [
            "<!-- Generated by scripts/analyse_idswitches.py.  Do not edit. -->",
            "",
            table(trackers),
            "",
            "Switches per hundred ground-truth detections: "
            + ", ".join(
                f"{name} {value}" for name, value in summary["switches_per_hundred_frames"].items()
            )
            + ".",
            "",
        ]
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    write_text_lf(args.out, markdown)
    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    write_text_lf(args.json_out, json.dumps(summary, indent=2) + "\n")

    if not args.quiet:
        print(markdown)
        print(f"wrote {args.out} and {args.json_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
